"""
scripts/py_lock.py -- the hash-pinned Python locks are well-formed, current, and installed.

Each test builds a small tree (a local package, a .in file, a lock, the recorded
fingerprints) in tmp_path and runs the script's `check` against it, offline: no uv,
no index. The negative controls are the point: a pyproject.toml whose dependency
changed without a re-lock must FAIL, and so must a pin below a floor, a pin without
a hash, and an environment that differs from its lock by one version, one missing
distribution or one extra.
"""

from __future__ import annotations

import importlib.util
import json
import stat
import subprocess
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from types import ModuleType

REPO = Path(__file__).resolve().parents[3]
SCRIPT = REPO / "scripts" / "py_lock.py"
HASH = "--hash=sha256:" + "ab" * 32


def _module() -> ModuleType:
    spec = importlib.util.spec_from_file_location("py_lock", SCRIPT)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    sys.modules["py_lock"] = mod  # dataclasses look their module up there
    spec.loader.exec_module(mod)
    return mod


def _tree(tmp_path: Path, deps: list[str], pins: list[str], *, record: bool = True) -> Path:
    """A root with pkg/ (a local package), requirements/demo.in and demo.txt."""
    root = tmp_path / "root"
    (root / "pkg").mkdir(parents=True)
    (root / "requirements").mkdir()
    (root / "pkg" / "pyproject.toml").write_text(
        '[build-system]\nrequires = ["hatchling"]\n\n'
        '[project]\nname = "demo-pkg"\nversion = "0.1"\n'
        f"dependencies = {json.dumps(deps)}\n"
        '[project.optional-dependencies]\ndev = ["pytest>=8"]\n'
    )
    (root / "requirements" / "demo.in").write_text("# inputs\n-e ./pkg[dev]\n")
    (root / "requirements" / "demo.txt").write_text(
        "# This file was autogenerated by uv\n"
        + "".join(f"{p} \\\n    {HASH}\n    # via demo-pkg\n" for p in pins)
    )
    if record:
        _record(root)
    return root


def _record(root: Path) -> None:
    """What `relock` writes after resolving: the fingerprint of the inputs as they are now."""
    mod = _module()
    data = {"locks": {"demo": {"inputs": mod.fingerprint("demo", root)}}}
    (root / "requirements" / "lock-inputs.json").write_text(json.dumps(data))


def _check(root: Path, *extra: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), "--root", str(root), "check", "demo", *extra],
        capture_output=True, text=True, check=False,
    )


def _fake_python(tmp_path: Path, dists: dict[str, str], pip_check_rc: int = 0) -> Path:
    """An interpreter that reports these installed distributions and this `pip check` result."""
    real = subprocess.run(
        [sys.executable, "-c", _module().PROBE], capture_output=True, text=True, check=True
    )
    markers = json.loads(real.stdout)["markers"]
    exe = tmp_path / "fakepython"
    exe.write_text(
        f"#!{sys.executable}\n"
        "import json, sys\n"
        "if sys.argv[1:3] == ['-m', 'pip']:\n"
        f"    print('pip check output'); sys.exit({pip_check_rc})\n"
        f"print(json.dumps({{'markers': {markers!r}, 'dists': {dists!r}}}))\n"
    )
    exe.chmod(exe.stat().st_mode | stat.S_IEXEC)
    return exe


GOOD_DEPS = ["six>=1.10", "idna>=3; python_version < '3'"]  # the second's marker never holds
GOOD_PINS = ["six==1.16.0", "pytest==8.3.0", "colorama==0.4.6 ; sys_platform == 'win32'"]


def test_a_current_well_formed_lock_passes(tmp_path: Path) -> None:
    proc = _check(_tree(tmp_path, GOOD_DEPS, GOOD_PINS))
    assert proc.returncode == 0, proc.stdout
    assert "python-lock: 1 locks, 3 pins, every one hashed, inputs current" in proc.stdout


def test_a_dependency_edit_without_relock_fails(tmp_path: Path) -> None:
    # The negative control the step exists for: the floor moves, the lock does not.
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    pp = root / "pkg" / "pyproject.toml"
    pp.write_text(pp.read_text().replace('"six>=1.10"', '"six>=1.11"'))
    proc = _check(root)
    assert proc.returncode == 1
    assert "the lock is stale -- changed since it was made: pkg/pyproject.toml" in proc.stdout
    assert "python3 scripts/py_lock.py relock" in proc.stdout


def test_an_edit_outside_the_dependency_tables_does_not_invalidate_the_lock(tmp_path: Path) -> None:
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    pp = root / "pkg" / "pyproject.toml"
    pp.write_text(pp.read_text().replace('version = "0.1"', 'version = "0.2"\ndescription = "x"'))
    assert _check(root).returncode == 0


def test_an_edit_to_the_in_file_without_relock_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    (root / "requirements" / "demo.in").write_text("-e ./pkg[dev]\nrequests\n")
    proc = _check(root)
    assert proc.returncode == 1 and "requirements/demo.in" in proc.stdout


def test_a_pin_below_a_floor_fails_even_when_the_fingerprint_is_current(tmp_path: Path) -> None:
    root = _tree(tmp_path, ["six>=1.17"], GOOD_PINS)  # fingerprint recorded, lock hand-made wrong
    proc = _check(root)
    assert proc.returncode == 1
    assert "requires 'six>=1.17'; the lock pins six==1.16.0" in proc.stdout


def test_a_requirement_the_lock_lacks_fails(tmp_path: Path) -> None:
    proc = _check(_tree(tmp_path, [*GOOD_DEPS, "attrs>=23"], GOOD_PINS))
    assert proc.returncode == 1 and "the lock does not pin attrs" in proc.stdout


def test_a_pin_without_a_hash_or_a_range_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    lock = root / "requirements" / "demo.txt"
    lock.write_text(lock.read_text() + "attrs==23.1.0\nrequests>=2 \\\n    " + HASH + "\n")
    proc = _check(root)
    assert proc.returncode == 1
    assert "attrs==23.1.0 has no --hash" in proc.stdout
    assert "`requests>=2` is not name==version" in proc.stdout


def test_no_recorded_fingerprint_fails(tmp_path: Path) -> None:
    proc = _check(_tree(tmp_path, GOOD_DEPS, GOOD_PINS, record=False))
    assert proc.returncode == 1 and "no fingerprint" in proc.stdout


def test_an_environment_equal_to_the_lock_passes(tmp_path: Path) -> None:
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    py = _fake_python(tmp_path, {"six": "1.16.0", "pytest": "8.3.0", "demo_pkg": "0.1"})
    proc = _check(root, "--env", f"demo={py}")
    assert proc.returncode == 0, proc.stdout
    assert "env demo = lock (2 dists)" in proc.stdout  # colorama's marker does not hold here


def test_an_environment_that_differs_from_the_lock_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    py = _fake_python(tmp_path, {"six": "1.17.0", "ipython": "9.0", "demo-pkg": "0.1"})
    proc = _check(root, "--env", f"demo={py}")
    assert proc.returncode == 1
    assert "env demo: six is 1.17.0 installed, 1.16.0 locked" in proc.stdout
    assert "env demo: pytest==8.3.0 is locked, not installed" in proc.stdout
    assert "env demo: ipython==9.0 is installed, not in the lock" in proc.stdout
    assert "py_lock.py sync demo" in proc.stdout


def test_an_environment_whose_pip_check_fails_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    dists = {"six": "1.16.0", "pytest": "8.3.0", "demo-pkg": "0.1"}
    py = _fake_python(tmp_path, dists, pip_check_rc=1)
    proc = _check(root, "--env", f"demo={py}")
    assert proc.returncode == 1 and "pip check failed" in proc.stdout


def test_the_local_package_must_be_installed(tmp_path: Path) -> None:
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    py = _fake_python(tmp_path, {"six": "1.16.0", "pytest": "8.3.0"})
    proc = _check(root, "--env", f"demo={py}")
    assert proc.returncode == 1 and "the local package demo-pkg is not installed" in proc.stdout


def test_the_repository_locks_are_current() -> None:
    # The committed locks, as the gate's python-lock step checks them (without an env).
    proc = subprocess.run(
        [sys.executable, str(SCRIPT), "check"], capture_output=True, text=True, check=False
    )
    assert proc.returncode == 0, proc.stdout
    for name in ("backend", "kernel", "image"):
        assert f"ok   {name}:" in proc.stdout


def _fake_uv(tmp_path: Path) -> tuple[Path, Path]:
    """A `uv` that records each argv (one JSON list per line) and succeeds."""
    log = tmp_path / "uv-calls.jsonl"
    exe = tmp_path / "fakeuv"
    exe.write_text(
        f"#!{sys.executable}\n"
        "import json, sys\n"
        f"with open({str(log)!r}, 'a') as fh:\n"
        "    fh.write(json.dumps(sys.argv[1:]) + '\\n')\n"
        "if sys.argv[1:] == ['--version']:\n"
        "    print('uv 0.0.0 (fake)')\n"
    )
    exe.chmod(exe.stat().st_mode | stat.S_IEXEC)
    return exe, log


def test_relock_refreshes_every_local_package(tmp_path: Path) -> None:
    # uv caches a built wheel of a local package by path; after its version bumps
    # (causal-core 0.10 -> 0.11) a relock resolved against the stale cached build
    # until UV_NO_CACHE=1. relock must ask uv to rebuild each local package it
    # names (--refresh-package), leaving the cache for index packages alone.
    root = _tree(tmp_path, GOOD_DEPS, GOOD_PINS)
    (root / "other").mkdir()
    (root / "other" / "pyproject.toml").write_text(
        '[project]\nname = "Other_Pkg"\nversion = "2.0"\ndependencies = []\n'
    )
    (root / "requirements" / "demo.in").write_text("-e ./pkg[dev]\n./other\nsix\n")
    uv, log = _fake_uv(tmp_path)
    proc = subprocess.run(
        [sys.executable, str(SCRIPT), "--root", str(root), "relock", "demo"],
        capture_output=True, text=True, check=False, env={"UV": str(uv), "PATH": ""},
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    calls = [json.loads(line) for line in log.read_text().splitlines()]
    compile_cmd = next(c for c in calls if c[:2] == ["pip", "compile"])
    refreshed = [compile_cmd[i + 1] for i, a in enumerate(compile_cmd) if a == "--refresh-package"]
    assert sorted(refreshed) == ["demo-pkg", "other-pkg"]
    # Only the local packages: a blanket --refresh / --no-cache would refetch the world.
    assert "--refresh" not in compile_cmd and "--no-cache" not in compile_cmd
