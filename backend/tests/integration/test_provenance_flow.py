"""
Provenance is written by the flows that run, and read back through the API.

Written for septa-16 (register entry `provenance-store-no-callers`). ADR-002 says
provenance records capture the chain from source data to the final artefact, and
the provenance API served them -- but `store_provenance_record` had no call site,
so the API served only what a test had put there.

Which ADR-002 sources run today, and so which are asserted here:
  - a reasoning session (POST /api/v1/session/run, POST /api/v1/session/incident);
  - a Guardian check (GovernanceAgent.check, reached by POST /api/governance/check
    and by the GuardianCheck node of every session);
  - a decision (POST /api/v1/decisions), recorded under session
    `decision:<entry_digest>`.
The LLM capture hook is wired to the durable store (last test), but no runtime
path calls get_llm (register `llm-routing-no-callers`), so no flow produces an
LLM invocation, and none is asserted of a flow.

Preconditions: the app runs on the db_engine fixture (SQLite, or PostgreSQL as
causal_app); the caller authenticates with a mocked token; reads use a
governance role, which every provenance route requires.

Postconditions:
  - after a session run, GET /api/v1/provenance/trace/{session_id} returns the
    AGENT, the run's ACTIVITY, and one output ENTITY generated by that activity
    and derived from what the activity used, carrying the run's verdict; the
    description the user typed is not in the trace;
  - the trace is complete (no dangling link) and a new store reads the same
    records (they live in the database, not in the process);
  - an incident session's Guardian check leaves a Guardian ACTIVITY in that
    session citing an audit_log row written for it;
  - POST /api/governance/check leaves a Guardian ACTIVITY in its session whose
    guardian_verdict_ref is the audit_entry_id the check returned;
  - POST /api/v1/decisions leaves, under `decision:<entry_digest>`, an ENTITY
    naming that entry digest and verdict, generated by an ACTIVITY that used the
    data and graph entities;
  - an LLM call through the capture wrapper is persisted and listed by
    GET /api/v1/provenance/invocations/{session_id}.

Undefined, not asserted: record ids, labels' exact wording, the order of the
records beyond generation order, timestamps.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any
from unittest.mock import AsyncMock, patch

import pytest
from httpx import ASGITransport, AsyncClient
from sqlalchemy import text

from src.api.main import app
from src.semantic_layer.provenance_store import ProvenanceStore
from tests.integration.test_decision_ledger import body as decision_body

if TYPE_CHECKING:
    from sqlalchemy.ext.asyncio import AsyncSession

pytestmark = pytest.mark.asyncio

ANALYST: dict[str, Any] = {"uid": "prov-analyst", "roles": ["analyst"]}
SRE: dict[str, Any] = {"uid": "prov-sre", "roles": ["sre"]}
AUTHOR: dict[str, Any] = {"uid": "prov-author", "roles": ["graph_author"]}
OFFICER: dict[str, Any] = {"uid": "prov-officer", "roles": ["governance_officer"]}


class _As:
    """An AsyncClient on the app, authenticated as `user`."""

    def __init__(self, user: dict[str, Any]) -> None:
        self._user = user

    async def __aenter__(self) -> AsyncClient:
        self._patch = patch(
            "src.middleware.auth._verify_firebase_token",
            new_callable=AsyncMock,
            return_value=self._user,
        )
        self._patch.start()
        self._client = AsyncClient(
            transport=ASGITransport(app=app),
            base_url="http://test",
            headers={"Authorization": "Bearer test-token"},
        )
        return await self._client.__aenter__()

    async def __aexit__(self, *exc: object) -> None:
        await self._client.__aexit__(*exc)
        self._patch.stop()


async def _trace(session_id: str) -> dict[str, Any]:
    async with _As(OFFICER) as client:
        resp = await client.get(f"/api/v1/provenance/trace/{session_id}")
    assert resp.status_code == 200, resp.text
    return dict(resp.json())


def _of_type(trace: dict[str, Any], kind: str) -> list[dict[str, Any]]:
    return [r for r in trace["records"] if r["record_type"] == kind]


async def _audit_ids(db_session: AsyncSession, session_id: str) -> set[str]:
    rows = await db_session.execute(
        text("SELECT id FROM audit_log WHERE session_id = :sid"), {"sid": session_id}
    )
    return {str(r[0]) for r in rows}


async def test_a_session_run_leaves_a_provenance_trace(db_engine: object) -> None:
    async with _As(ANALYST) as client:
        resp = await client.post(
            "/api/v1/session/run",
            json={"description": "Latency rose after the deployment of service A."},
        )
    assert resp.status_code == 200, resp.text
    sid = resp.json()["session_id"]

    trace = await _trace(sid)
    agents = _of_type(trace, "AGENT")
    activities = _of_type(trace, "ACTIVITY")
    entities = _of_type(trace, "ENTITY")
    assert [a["label"] for a in agents] == ["platform-agent"]

    runs = [a for a in activities if a["label"] == "POST /api/v1/session/run"]
    assert len(runs) == 1
    outputs = [e for e in entities if e["was_generated_by"] == runs[0]["id"]]
    assert len(outputs) == 1
    assert outputs[0]["attributes"]["guardian_verdict"] == resp.json()["guardian_verdict"]
    assert set(runs[0]["used"]) == set(outputs[0]["was_derived_from"])
    # The user's words are not copied into the trace; their digest is.
    assert "Latency rose" not in str(trace)

    assert trace["incomplete"] is False, trace
    # It is in the database, not in this process: a new store reads the same.
    fresh = await ProvenanceStore().read(sid)
    assert {str(r.id) for r in fresh.records} == {r["id"] for r in trace["records"]}


async def test_an_incident_session_records_its_guardian_check(
    db_engine: object, db_session: AsyncSession
) -> None:
    """The triage agent's Guardian check is recorded in the session it ran in,
    citing the audit_log row it wrote."""
    async with _As(SRE) as client:
        resp = await client.post(
            "/api/v1/session/incident",
            json={
                "incident_id": "INC-PROV-1",
                "title": "Checkout latency",
                "severity": "P2",
                "affected_services": ["checkout"],
            },
        )
    assert resp.status_code == 200, resp.text
    sid = resp.json()["session_id"]
    trace = await _trace(sid)
    audit_ids = await _audit_ids(db_session, sid)
    assert audit_ids

    activities = _of_type(trace, "ACTIVITY")
    guardian = [a for a in activities if a["label"] == "Guardian check"]
    assert guardian and {a["guardian_verdict_ref"] for a in guardian} <= audit_ids

    runs = [a for a in activities if a["label"] == "POST /api/v1/session/incident"]
    assert len(runs) == 1
    assert any(e["was_generated_by"] == runs[0]["id"] for e in _of_type(trace, "ENTITY"))
    assert trace["incomplete"] is False, trace


async def test_a_guardian_check_leaves_an_activity_citing_its_audit_row(
    db_engine: object,
) -> None:
    sid = "prov-guardian-check"
    async with _As(AUTHOR) as client:
        resp = await client.post(
            "/api/governance/check",
            json={
                "action_type": "EDGE_PROPOSAL",
                "cynefin_domain": "COMPLICATED",
                "payload": {"source": "a", "target": "b", "confidence": 0.8},
                "session_id": sid,
            },
        )
    assert resp.status_code == 200, resp.text
    audit_entry_id = resp.json()["audit_entry_id"]

    trace = await _trace(sid)
    cited = [r for r in _of_type(trace, "ACTIVITY") if r["guardian_verdict_ref"] == audit_entry_id]
    assert len(cited) == 1
    assert cited[0]["attributes"]["verdict"] == resp.json()["verdict"]
    assert cited[0]["attributes"]["action_type"] == "EDGE_PROPOSAL"


async def test_a_decision_leaves_a_provenance_trace_under_its_entry_digest(
    db_engine: object,
) -> None:
    async with _As(SRE) as client:
        resp = await client.post("/api/v1/decisions", json=decision_body())
    assert resp.status_code == 200, resp.text
    record = resp.json()["record"]

    trace = await _trace(f"decision:{record['entry_digest']}")
    activities = {a["id"]: a for a in _of_type(trace, "ACTIVITY")}
    decided = [
        e
        for e in _of_type(trace, "ENTITY")
        if e["attributes"].get("entry_digest") == record["entry_digest"]
    ]
    assert len(decided) == 1
    assert decided[0]["attributes"]["verdict"] == resp.json()["verdict"]
    activity = activities[decided[0]["was_generated_by"]]
    inputs = {e["id"] for e in _of_type(trace, "ENTITY")} - {decided[0]["id"]}
    assert set(activity["used"]) == inputs and len(inputs) == 2
    assert trace["incomplete"] is False, trace


async def test_the_llm_capture_hook_persists_an_invocation(db_engine: object) -> None:
    """get_llm has no runtime caller (llm-routing-no-callers); the hook it would
    use writes to the durable store, and the API lists what it wrote."""
    from src.agents.llm_factory import _wrap_with_invocation_capture

    class _Stub:
        async def ainvoke(self, prompt: Any, **_: Any) -> str:
            return f"echo: {prompt}"

    sid = "prov-llm-hook"
    llm = _wrap_with_invocation_capture(
        _Stub(),
        session_id=sid,
        agent_id="stub-agent",
        provider="ollama",
        model_name="stub-model",
        capability="fast_classification",
    )
    assert await llm.ainvoke("hello") == "echo: hello"

    async with _As(OFFICER) as client:
        resp = await client.get(f"/api/v1/provenance/invocations/{sid}")
    assert resp.status_code == 200, resp.text
    listed = resp.json()
    assert [i["model_name"] for i in listed] == ["stub-model"]
    assert listed[0]["agent_id"] == "stub-agent"
